"""Preserve source database properties only in generated fresh proof databases."""
import hashlib, importlib.util, re, subprocess, sys
from pathlib import Path
from scope import DB_ID, DATABASE, require, verify_properties

OPS=Path('/home/nathaniel/.local/state/openplan/gtfs-light-mode-join-20261011/openplan/scripts/ops')
sys.path.insert(0,str(OPS))
spec=importlib.util.spec_from_file_location('expanded_archive_ops',OPS/'full_restore.py')
archive=importlib.util.module_from_spec(spec);spec.loader.exec_module(archive)

def fresh(name):
    require(re.fullmatch(r'openplan_attempt_cli_[0-9a-f]{32}',name),'expanded-property-target')

def sql(database,query):
    require(database in (DATABASE,'postgres','template1') or re.fullmatch(r'openplan_attempt_cli_[0-9a-f]{32}',database),'expanded-property-source')
    result=subprocess.run(['docker','exec',DB_ID,'psql','-U','supabase_admin','-d',database,'-XqAt','-v','ON_ERROR_STOP=1','-c',query],capture_output=True,text=True,timeout=90)
    require(result.returncode==0,'expanded-property-query')
    return result.stdout.strip()

def read(database):return archive.database_properties(DB_ID,database)

def property_commands(source,target):
    fresh(target)
    require(source==DATABASE or re.fullmatch(r'openplan_attempt_cli_[0-9a-f]{32}',source),'expanded-property-source')
    delegated=int(sql(source,"SELECT count(*) FROM pg_database d,LATERAL aclexplode(coalesce(d.datacl,acldefault('d',d.datdba))) a WHERE d.datname=current_database() AND a.grantor<>d.datdba"))
    verify_properties(read(source),delegated)
    # PostgreSQL quotes the captured grantors, grantees and setting values. The
    # generated target identifier never comes from an arbitrary user payload.
    commands=sql(source,"SELECT format('SET ROLE %I; REVOKE ALL PRIVILEGES ON DATABASE %I FROM PUBLIC; REVOKE ALL PRIVILEGES ON DATABASE %I FROM %I;',pg_get_userbyid(datdba),'"+target+"','"+target+"',pg_get_userbyid(datdba)) FROM pg_database WHERE datname=current_database()")
    commands+='\n'+sql(source,"SELECT format('GRANT %s ON DATABASE %I TO %s%s;',a.privilege_type,'"+target+"',CASE WHEN a.grantee=0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(a.grantee)) END,CASE WHEN a.is_grantable THEN ' WITH GRANT OPTION' ELSE '' END) FROM pg_database d,LATERAL aclexplode(coalesce(d.datacl,acldefault('d',d.datdba))) a WHERE d.datname=current_database() ORDER BY a.grantee,a.privilege_type")
    commands+='\nRESET ROLE;\n'+sql(source,"SELECT format('ALTER DATABASE %I CONNECTION LIMIT %s;','"+target+"',datconnlimit) FROM pg_database WHERE datname=current_database()")
    commands+='\n'+sql(source,"SELECT CASE WHEN s.setrole=0 THEN format('ALTER DATABASE %I SET %I TO %L;','"+target+"',split_part(item,'=',1),substr(item,strpos(item,'=')+1)) ELSE format('ALTER ROLE %I IN DATABASE %I SET %I TO %L;',r.rolname,'"+target+"',split_part(item,'=',1),substr(item,strpos(item,'=')+1)) END FROM pg_db_role_setting s LEFT JOIN pg_roles r ON r.oid=s.setrole,LATERAL unnest(s.setconfig) item WHERE s.setdatabase=(SELECT oid FROM pg_database WHERE datname=current_database())")
    return commands

def creation_args(database,properties,existing):
    fresh(database);verify_properties(properties,0)
    require(database not in existing,'expanded-property-existing')
    args=['docker','exec',DB_ID,'createdb','-U','supabase_admin','-T','template0','--owner',properties['owner'],'--encoding',properties['encoding'],'--lc-collate',properties['collate'],'--lc-ctype',properties['ctype']]
    if properties['localeProvider']=='i':args+=['--locale-provider','icu','--icu-locale',properties['locale']]
    return [*args,database]

def verify_command(target,commands,expected):
    fresh(target)
    require(expected['target']==target,'expanded-property-command-target')
    require(hashlib.sha256(commands.encode()).hexdigest()==expected['sha256'],'expanded-property-command-bytes')

def apply(target,commands,expected,out):
    verify_command(target,commands,expected)
    # Every target occurrence is generated by PostgreSQL format(), not replaced
    # inside captured setting values or credentials after generation.
    result=subprocess.run(['docker','exec','-i',DB_ID,'psql','-U','supabase_admin','-d','template1','-Xq','-v','ON_ERROR_STOP=1','--single-transaction'],input=commands,capture_output=True,text=True,timeout=90)
    (out/'database-properties-apply-private.log').write_text(result.stdout+result.stderr)
    require(result.returncode==0,'expanded-property-apply')
